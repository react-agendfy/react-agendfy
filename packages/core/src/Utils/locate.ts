/** Case/separator-insensitive index: 'ptbr' → ptBR, 'ptpt' → pt, ... */
const compactMap: Record<string, Locale> = {};
Object.entries(localeMap).forEach(([key, locale]) => {
  compactMap[key.toLowerCase()] = locale;
});

/**
 * Resolves a date-fns locale for a language tag.
 * Lookup order:
 *  1. exact legacy key ('ptBR', 'enGB', ...);
 *  2. case/separator-insensitive tag ('pt-BR', 'PT-pt', 'pt_br', ...);
 *  3. base language region-fallback ('de-AT' → 'de');
 *  4. enUS.
 */
export const getLocale = (lang?: string): Locale => {
  if (!lang) return enUS;
  if (localeMap[lang]) return localeMap[lang];
  const compact = lang.toLowerCase().replace(/[-_]/g, "");
  if (compactMap[compact]) return compactMap[compact];
  const base = lang.toLowerCase().split(/[-_]/)[0];
  return compactMap[base] ?? enUS;
};
